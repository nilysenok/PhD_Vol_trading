def hd(t: dict) -> list:
    h = t["HD"]
    return ["## 2. HD (описание по сохранённому ZB; D_ZB = l(ZB) − l(X1), дни E после включения)", "",
            md([[r.contrast, r.window, int(r.n), "%s: %d / %s: %d" % (r.group_a, r.n_a, r.group_b, r.n_b), f(r.mean_a, 5), f(r.mean_b, 5), f(r.diff, 5), f(r.lo90, 5), f(r.hi90, 5), int(r.n_boot)] for r in h.itertuples()],
               ["контраст", "окно", "n", "группы", "среднее D (первая)", "среднее D (вторая)", "разность", "lo90", "hi90", "повторов"]), ""]


def cond(t: dict) -> list:
    return ["## 3. Условие L1–L3 (механически; записано в CHECKPOINT `Z2.condition` до любого счёта H1)", "", md([[r.item, r.text, "да" if r.value else "нет", r.detail] for r in t["CONDITION"].itertuples()], ["пункт", "что", "выполнено", "деталь"]), ""]


def h1(t: dict, num: dict) -> list:
    if "CRIT" not in t:
        return ["## 4. H1 и Hc", "", "Не запускались: условие ложно (раздел 3). Прогнозов, таблиц оценки и критериев K1–K5 нет.", ""]
    cr, pr = t["CRIT"], t["PAIRS"]
    return ["## 4. H1 и Hc: критерии K1–K5, правило 6.2, Холм N = %d (решение разработки, не подтверждение)" % num["n_holm"], "",
            md([[r.crit, r.name, f(r.value, 4), f(r.threshold, 3), "да" if r.passed else "нет"] for r in cr.itertuples()], ["критерий", "условие", "значение", "порог", "выполнено"]), "",
            md([[r.y, r.base, r.window, int(r.n), f(r.base_qlike), f(r.y_qlike), f(r.delta_pct, 2), f(r.lo90, 2), f(r.hi90, 2), f(r.p_one, 3), f(r.p_holm_N, 3)] for r in pr.itertuples() if r.window in PW],
               ["ряд", "база", "окно", "n", "QLIKE базы", "QLIKE", "Δ %", "lo90", "hi90", "DM p", "p Холм N"]), ""]


def notes(num: dict) -> list:
    return ["## 5. Трактовки и отступления", ""] + ["- " + x for x in NOTES] + [""]


def build(t: dict, num: dict) -> str:
    return "\n".join(head(t, num) + h0(t, num) + hd(t) + cond(t) + h1(t, num) + notes(num))
