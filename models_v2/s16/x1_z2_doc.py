def head(t: dict, num: dict) -> list:
    c = t["CONDITION"].set_index("item")
    out = ["Статус: %s (Ж-246 п. 6; SBER, h = 1; первая цифра — потолок)." % STATUS, "", "# Этап Z2 — предпроверки H0 / HD и условие L1–L3 для Hawkes-переноса шока (H1 + Hc), SBER, h = 1", ""]
    if bool(c.at["условие", "value"]):
        return out + ["**Условие L1–L3 истинно → H1 и Hc считались** (разделы 6–9).", ""]
    return out + ["**H1 и Hc не запускались: условие L1–L3 ложно** (%s). H2 не считается без решения владельца. Конфигураций израсходовано: %d (реестр: %s); N Холма остаётся %d." % (c.at["условие", "detail"].replace("ложные: ", ""), num["configs_spent"], num["registered_at"], num["n_holm_z"]), ""]


