from __future__ import annotations

import pandas as pd

from models_v2.s12 import v5_dx1_mom as MO


def mom_block(m: pd.DataFrame, win: str) -> list:
    g = m[(m["window"] == win)]
    rows = ["| k | m K8 | t K8 | m M | t M |", "|---|---|---|---|---|"]
    for nm in MO.NAMES:
        a = g[(g["base"] == "K8") & (g["item"] == nm)].iloc[0]
        b = g[(g["base"] == "M") & (g["item"] == nm)].iloc[0]
        rows.append("| %s | %.4f | %.2f | %.4f | %.2f |" % (nm, a["m"], a["t_nw"], b["m"], b["t_nw"]))
    w = {x: g[(g["base"] == x) & (g["item"] == "wald")].iloc[0] for x in ("K8", "M")}
    rows.append("Вальд: K8 W = %.1f, df = %d, p = %.3g; M W = %.1f, df = %d, p = %.3g." % (w["K8"]["wald"], w["K8"]["df"], w["K8"]["p_wald"], w["M"]["wald"], w["M"]["df"], w["M"]["p_wald"]))
    return rows


