"""S-C-EVAL, документ (Ж-254 п. 16; `S_C_SPEC.md`, разд. 7): разделы 7–8 отчёта — параметры по годам, число обученных вариантов и подгонок, стоимость и воспроизводимость, ответ «что дало разложение риска».
Публичное API: `sec7(T, ck)` — `ck` = ключ `S.C.eval` из CHECKPOINT (sha256 входов и кода, written_at); `sec8(T)` — ответ из таблиц: К1 / К2 / К3, абляция C-KA, прямая коррекция C-D к W5-G, список вариантов, лучших W5-G по QLIKE; `answer(k1, k2, k3)` — формулировка по знакам Δ.
Текст строится только из таблиц `S_C_*.csv` и ключа CHECKPOINT."""
from __future__ import annotations

from models_v2.s18.cm_doc_fmt import c_, dm_line, md, stat, word

COST = ("Стоимость: счёт пяти вариантов — по `GATES_S.md` (W.G7, оценка кодера листа IMPL-3, не замер CPU) порядка 5 с на вариант при 4 процессах; спецификация (разд. 3) оценивала верхнюю границу ≤ 1 CPU-ч. "
        "Оценка этого этапа (SPA, StepM, бутстрап B = 10 000, MCS) — в пределах минут; CPU-часы в таблицах не фиксируются.")
VARS = (("S-CD", "прямая коррекция (6)"), ("S-CK", "компонентный (6)"), ("S-CKA", "компонентный + потеря по частям (6)"), ("S-CKL", "компонентный, разложение сдвинуто (6)"))


def _ptab(P, var) -> str:
    y = P[(P["variant"] == var) & (P["level"] == "year")].dropna(axis=1, how="all")
    th = [k for k in y.columns if k not in ("variant", "level", "key", "n", "lam", "spread", "spread_max", "nz0", "seed_best")]
    rows = [[r["key"], int(r["n"]), c_(r["lam"], 5), c_(r["nz0"], 2), c_(r["spread"], 6), c_(r["spread_max"], 6)] + [c_(r[k], 4, True) for k in th] for _, r in y.iterrows()]
    return md(["Год D", "переоценок", "λ (среднее)", "‖θ‖₀ (модуль θ > 1e-6), среднее", "разброс L (среднее)", "разброс L (макс.)"] + th, rows)


def sec7(T: dict, ck: dict) -> str:
    P = T["params"]
    f = P[P["level"] == "fits"]
    fits = md(["Вариант", "подгонки", "число подгонок L-BFGS-B"], [[r.variant, r.key, int(r.n)] for r in f.itertuples()])
    sha = ", ".join("%s %s" % (k.replace("data/", "").replace("docs/otchety/", ""), v[:16]) for k, v in sorted(ck["inputs"].items()))
    code = ", ".join("%s %s" % (k, v[:16]) for k, v in sorted(ck["code"].items()))
    tabs = "\n\n".join("### %s — %s\n\n%s" % (v, w, _ptab(P, v)) for v, w in VARS)
    return ("## 7. Параметры, число обученных вариантов, стоимость, воспроизводимость\n\n" + dm_line(T) + " Параметры по годам (среднее по месячным переоценкам года; D — первый торговый день месяца, переоценки внутри этого окна); все месяцы и варианты — `S_C_PARAMS.csv`. "
            "«Разброс L» — разность максимума и минимума штрафованной функции потерь по 5 перезапускам. S-C7 параметров не имеет (внутри — МНК HAR-J компонент, общий вход всех вариантов).\n\n" + tabs +
            "\n\nЧисло реально обученных вариантов: 4 (S-CD, S-CK, S-CKA, S-CKL; S-C7 — без обучения) из 5 зарегистрированных; S-C2f, S-C7i, S-CDx, S-CDw не запускались и в N не входят. Подгонки:\n\n" + fits +
            "\n\n" + COST + "\n\nВоспроизводимость (sha256, первые 16 знаков; ключ `S.C.eval` в `docs/otchety/harj_x1/CHECKPOINT.json`, written_at " + ck["written_at"] + "): входы — " + sha + "; код — " + code + ".")


def answer(k1: float, k2: float, k3: float) -> str:
    if k1 < 0 and k2 < 0 and k3 < 0:
        return "разложение риска дало численный эффект над прямой коррекцией, K7-классом и сдвинутым разложением"
    if k1 >= 0 and k2 >= 0:
        return "разложение риска не дало численного выигрыша ни над прямой коррекцией на тех же входах (К1), ни над K7-классом (К2): остаётся дополнительная сложность"
    return "разложение риска дало численный выигрыш только по части контролей (К1 %s, К2 %s, К3 %s); условие «эффект структуры» не выполнено" % (word(k1), word(k2), word(k3))


def _ab(T, hid, kind) -> str:
    s = stat(T, hid, kind)
    return "%s %% (p DM %s, %s)" % (c_(s["delta_pct"], 4, True), c_(s["p_dm"], 4), word(s["delta_pct"]))


def sec8(T: dict) -> str:
    t = T["table"].set_index("series")
    k = {i: stat(T, i, "struct")["delta_pct"] for i in ("К1", "К2", "К3")}
    better = [v for v, _ in VARS + (("S-C7", ""),) if t.at[v, "d_W5-G_pct"] < 0]
    m1, m2 = stat(T, "S-CK|X1"), stat(T, "S-CK|W5-G")
    return ("## 8. Ответ: что дало разложение риска\n\nИз таблиц разделов 1–7; все сравнения — исследовательские, на раскрытой истории (не OOS); p структурных строк и абляции — без поправки, кроме указанного Холма.\n\n"
            "- **C-K против C-D (К1, разложение как структура):** " + _ab(T, "К1", "struct") + ".\n"
            "- **C-K против C-KL (К3, привязка разложения ко времени):** " + _ab(T, "К3", "struct") + ".\n"
            "- **C-K против C-7 (К2, обучение внутри гибрида против раздельных HAR):** " + _ab(T, "К2", "struct") + ".\n"
            "- **C-KA против C-K (дополнительная компонентная задача):** F — " + _ab(T, "S-CKA|S-CK F", "ablation") + "; слой X1_C — " + _ab(T, "S-CKA|S-CK слой X1_C", "ablation") + ".\n"
            "- **C-D против W5-G (рыночные признаки без структуры, «дополнительная гибкость»):** " + _ab(T, "S-CD|W5-G", "cd_base") + " (сырой p, справочно).\n"
            "- **Против контрольных версий:** S-CK к X1 (слой, М1) %s %% (p DM %s), F к W5-G (М2) %s %% (p DM %s); решения этапа — раздел 5.\n" % (c_(m1["delta_pct"], 4, True), c_(m1["p_dm"], 4), c_(m2["delta_pct"], 4, True), c_(m2["p_dm"], 4)) +
            "- **Варианты C численно лучше W5-G по QLIKE (таблица 1):** " + (", ".join(better) if better else "ни один") + ".\n\n"
            "Ответ из таблиц: " + answer(k["К1"], k["К2"], k["К3"]) + ". " + T["guard"][T["guard"]["id"] == "решение STRUCT"]["value"].iloc[0] + ". "
            "Вывод ограничен таблицами: численное улучшение, прохождение ограничений и статистическая подтверждённость различаются (раздел 5); независимого подтверждения нет.")
