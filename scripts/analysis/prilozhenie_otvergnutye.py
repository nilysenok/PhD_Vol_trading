def expand(src):
    """'d14:25; FD:708; otk/X.yaml:12; regen/D23/x.csv:4' -> полные пути"""
    out = []
    for tok in [t.strip() for t in src.split(';') if t.strip()]:
        name, _, line = tok.partition(':')
        if name in PREFIX:
            path = PREFIX[name]
        elif name.startswith('otk/'):
            path = 'data/regen/final3/otkloneno/' + name[4:]
        elif name.startswith('regen/'):
            path = 'data/' + name
        elif re.fullmatch(r'd\d\d[a-z0-9_]*', name):
            path = f'docs/otchety/2026-10-26_{name}.md'
        else:
            raise ValueError(f'неизвестный источник: {tok}')
        out.append(f'{path}:{line}' if line else path)
    return '; '.join(out)


