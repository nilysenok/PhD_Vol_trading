YEAR_RE = re.compile(r'(?<!\d)20(2[2-9])(?!\d)')


def check():
    """только разработочный набор: в тексте строк нет лет ≥ 2022; счёт «нет в отчёте»"""
    for i, r in enumerate(ROWS, 1):
        assert len(r) == 8, (i, r)
        for f in r[:7]:
            m = YEAR_RE.search(f)
            assert not m, f'строка {i}: год {m.group(0)} в «{f}»'
        expand(r[7])
    for r in ACCEPTED:
        for f in r[:7]:
            assert not YEAR_RE.search(f), r
    return sum((r[3] == NET) + (r[4] == NET) for r in ROWS)


