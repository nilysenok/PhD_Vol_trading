"""Отчёт cd_s3_test_c: все числа берутся из посчитанных таблиц."""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

from cd_s3_report import _tab


def napisat(path: Path, df: pd.DataFrame, sd: pd.DataFrame, msr_k2: np.ndarray, p_k2: float, svod: dict, sverka: int, sek: float) -> None:
    g = df[df.god == "2018-2019"]
    h = g[g.tip == "H2"].iloc[0]
    first = (f"**Δ mSR (H2, затвор C1 W504 p70 по σ̂ гибрида h5) против базы: {h.d_vs_baza:+.3f}; против HAR-J (б) h5: {h.d_vs_harj:+.3f}** "
             f"(S3, 2018–2019, плата за шорт 5 %, Δ = разность табличных mSR; p к2 по 100 сдвигам = {p_k2:.2f}). "
             f"Разработка, потолок, H2-строка по TEST_C.")
    d1 = sd[sd.ryad == "hyb"]
    k_lv, k_pr = int(d1.loc[d1["corr"].idxmax(), "sdvig"]), int(d1.loc[d1["corr_prirasch"].idxmax(), "sdvig"])
    d1_txt = (f"**Д1 (σ̂ h5, гибрид): максимум корреляции с √RV при k = {k_lv} (уровни) и k = {k_pr} (приращения); "
              "k = −1 — последний известный день, сдвига в будущее нет.**" if k_pr == -1
              else "**Д1: максимум по приращениям не на k = −1 — СДВИГ, ряд блокируется.**")
    first = first + "\n\n" + d1_txt
    parts = []
    for col, nm in (("corr", "уровни"), ("corr_prirasch", "приращения")):
        t = sd.pivot(index="ryad", columns="sdvig", values=col).reset_index()
        t.columns = [str(c) for c in t.columns]
        mx = {r: int(x.loc[x[col].idxmax(), "sdvig"]) for r, x in sd.groupby("ryad")}
        parts.append(f"{nm}; максимум по k: {mx}\n{_tab(t, list(t.columns))}")
    sv = "; ".join(f"{k}: закрыто {v['zakryto']} из {v['dney']} дней, ранг не определён {v['nan']}" for k, v in svod.items())
    txt = f"""{first}

**Статус: разработка train4, окно 2018–2019, потолок.** Не результат теста. Конфигурация C заморожена владельцем (`fastbt/s9.py`: `TEST_C = C1:W504_p70`, `hyb_h5`),
не подбиралась здесь; сами дизайны A/S3 выбраны на тех же train4 — честной половины нет. Данные ≥ 2020 не читались, метрики 2020–2021 не считались.

## Проверка сдвига σ̂ h5 (Д1)
Корреляция σ̂ (строка d, известна на close d) с √RV дня d+1+k, пул по 17 тикерам, 2018–2019. k = −1 — день d, k = 0 — d+1, k = +1 — d+2. σ̂ h5 — средний
прогноз на d+1…d+5, поэтому максимум в уровнях допустим на k ∈ {{−1, 0}}; сдвиг в сторону будущего (k = +1) был бы утечкой.
{chr(10).join(parts)}

## Что в TEST_C и как это воспроизведено (отличия от диагностики #483)
- Ранг: σ_t против окна [t−504, t−1], **текущий бар не входит** (`s9_stats.past_rank`), доля строго ниже, нужно ≥ 252 значений (`s9._minp`, разгон 252 → 504); NaN → затвор открыт.
- Сторона: S3 — категория 0 (тренд, `s9.CATS`), затвор `G[0]`: торгуем при ранге **> 1 − p = 0,30**, т. е. закрыты дни с **низкой** σ̂ (нижние 30 %). В #483 было наоборот (закрыты высокие, ранг ≥ p67).
- Действие: побаровое — позиция × маска (`e.A_row * g`), закрывает и открытую позицию; в #483 затвор запрещал только вход (`gate_trades`).
- σ̂: `sigma_hyb_h5_dev` (контроли: `sigma_harj_b_h5_dev`, `sigma_naive_dev` — один ряд для h1/h5); выравнивание «последнее значение с датой ≤ бара», как `s9.align`.
- Сверка с s9: маска из `s9.past_rank` + `s9._c_gate` + `s9.CATS` против моей, 17 тикеров, до 2019: **расхождений {sverka}**.
- Затвор: {sv}.
- к2: круговой сдвиг маски по тикеру на lag ∈ [21, n−21], 100 повторов, seed 20261028; p = доля повторов с mSR ≥ mSR H2. mSR к2: среднее {msr_k2.mean():.3f}, 5 % {np.quantile(msr_k2, .05):.3f}, 95 % {np.quantile(msr_k2, .95):.3f}.
- Метрики: mSR (`fastbt/metriki_e.py`, Д7), Sharpe ddof = 1, √252, дневной excess с платой за шорт 5 %, комиссия 0,04 %; сделок = стороны/2.

## Результат (`docs/tables/cd_s3/test_c.csv`)
{_tab(df, ['stroka', 'tip', 'god', 'msr', 'sharpe', 'sdelok', 'd_vs_baza', 'd_vs_harj'])}

## Оговорки
- ↺ Окно 2018–2019, а не 2016–2019: σ̂ начинается 03.01.2017, рангу нужен прогрев ≥ 252 значений (в 2018 первые дни ранг не определён).
- Два года, 17 тикеров, одна пара S3: не статистика; Δ без доверительного интервала.
- Затвор режет экспозицию: Δ смешивает отбор и сокращение времени в позиции; к2 это контролирует.
- Не проверено: остальные Sk, другие W/p (заморожено), validation 2020–2021 (закрыта).
- Время счёта: {sek:.0f} с.
"""
    path.write_text(txt, encoding="utf-8")
